/**
 * Map captured GOVOne pages → per-slug markdown fragments for QLBD feature context.
 */

import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const DATA_ROOT = resolve(__dirname, "../..");
const OUT_DIR = resolve(
  DATA_ROOT,
  process.env.GOVONE_OUT_DIR || "docs/context/_raw/legacy-govone",
);
const PAGES_DIR = join(OUT_DIR, "pages");
const FEAT_DIR = join(OUT_DIR, "features");
const MAP_PATH = join(__dirname, "menu-slug-map.json");

function norm(s) {
  return String(s || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
}

function matchSlug(text, rules) {
  const n = norm(text);
  for (const r of rules) {
    for (const k of r.any || []) {
      if (n.includes(norm(k))) return r.slug;
    }
  }
  return "unmapped";
}

function loadPages() {
  if (!existsSync(PAGES_DIR)) return [];
  return readdirSync(PAGES_DIR)
    .filter((f) => f.endsWith(".json"))
    .map((f) => JSON.parse(readFileSync(join(PAGES_DIR, f), "utf8")));
}

function renderFeatureMd(slug, pages) {
  const lines = [
    `# Legacy GOVOne capture — \`${slug}\``,
    ``,
    `> Auto-generated by \`tools/legacy-govone-capture\`. Input cho \`/product-analy-demo\` · \`/qlbd-analy-demo\`.`,
    `> Source: https://pmdb.govone.vn — **không** chứa password.`,
    ``,
    `## Pages (${pages.length})`,
    ``,
  ];
  for (const p of pages) {
    lines.push(`### ${p.menuText || p.title || p.id}`);
    lines.push(``);
    lines.push(`- **id:** \`${p.id}\``);
    if (p.capturePath) {
      lines.push(`- **capture:** \`${p.capturePath}/\` (master/page/action)`);
    }
    lines.push(`- **url:** ${p.finalUrl || p.href || "—"}`);
    lines.push(`- **title:** ${p.title || "—"}`);
    if (p.headings?.length) {
      lines.push(`- **headings:** ${p.headings.slice(0, 12).join(" · ")}`);
    }
    if (p.formSample?.fields?.length || p.formSample?.labels?.length) {
      lines.push(``);
      lines.push(`#### Form sample (Create/Thêm)`);
      lines.push(``);
      lines.push(`- **trigger:** ${p.formSample.trigger || "create"}`);
      for (const l of [...new Set(p.formSample.labels || [])].slice(0, 40)) {
        lines.push(`- ${l}`);
      }
    }
    lines.push(``);
    if (p.labels?.length) {
      lines.push(`#### Labels / field captions`);
      lines.push(``);
      for (const l of [...new Set(p.labels)].slice(0, 80)) {
        lines.push(`- ${l}`);
      }
      lines.push(``);
    }
    if (p.fields?.length) {
      lines.push(`#### Inputs`);
      lines.push(``);
      lines.push(`| tag | type | name/id | placeholder |`);
      lines.push(`|-----|------|---------|-------------|`);
      for (const f of p.fields.slice(0, 80)) {
        const nid = f.name || f.id || "";
        lines.push(
          `| ${f.tag} | ${f.type || "—"} | ${nid || "—"} | ${(f.placeholder || "").slice(0, 40)} |`,
        );
      }
      lines.push(``);
    }
    if (p.tableHeaders?.length) {
      lines.push(`#### Grid columns`);
      lines.push(``);
      for (const h of [...new Set(p.tableHeaders)].slice(0, 60)) {
        lines.push(`- ${h}`);
      }
      lines.push(``);
    }
    if (p.actions?.length) {
      lines.push(`#### Actions / buttons (full)`);
      lines.push(``);
      lines.push(`| label | kind | zone | tag | disabled |`);
      lines.push(`|-------|------|------|-----|----------|`);
      for (const a of p.actions.slice(0, 120)) {
        lines.push(
          `| ${a.label} | ${a.kind || "—"} | ${a.zone || "—"} | ${a.tag || "—"} | ${a.disabled ? "yes" : ""} |`,
        );
      }
      lines.push(``);
      lines.push(`- **actionCount:** ${p.actionCount ?? p.actions.length}`);
      lines.push(``);
    } else if (p.buttons?.length) {
      lines.push(`#### Actions`);
      lines.push(``);
      for (const b of p.buttons.slice(0, 80)) {
        lines.push(`- ${b}`);
      }
      lines.push(``);
    }
  }
  lines.push(`## Migration notes`);
  lines.push(``);
  lines.push(
    `- Map fields/actions → \`npm run map:demo\` (modern MFE control-map · erp-form-context).`,
  );
  lines.push(
    `- Demo: same fields · Linm shell — **cấm** clone skin GOVOne · **cấm** BE.`,
  );
  lines.push(``);
  return lines.join("\n");
}

function main() {
  const map = JSON.parse(readFileSync(MAP_PATH, "utf8"));
  const rules = map.rules || [];
  const pages = loadPages();
  if (!pages.length) {
    console.error(`No pages in ${PAGES_DIR}. Run npm run capture first.`);
    process.exit(1);
  }

  mkdirSync(FEAT_DIR, { recursive: true });
  const bySlug = new Map();
  for (const p of pages) {
    if (/^\(apps-shell\)$/i.test(p.menuText || "") || p.kind === "shell") {
      continue; // shell catalog only — không gán 1 slug
    }
    // Prefer menu tile text for mapping (tránh heading chung “hạ tầng giao thông”)
    const hay = [p.menuText, p.title].join(" | ");
    const slug = matchSlug(hay, rules);
    if (!bySlug.has(slug)) bySlug.set(slug, []);
    bySlug.get(slug).push(p);
  }

  const index = {
    mappedAt: new Date().toISOString(),
    pageCount: pages.length,
    slugs: {},
  };

  for (const [slug, list] of [...bySlug.entries()].sort((a, b) =>
    a[0].localeCompare(b[0]),
  )) {
    const mdPath = join(FEAT_DIR, `${slug}.md`);
    writeFileSync(mdPath, renderFeatureMd(slug, list), "utf8");
    index.slugs[slug] = {
      pageCount: list.length,
      ids: list.map((p) => p.id),
      path: `features/${slug}.md`,
    };
    console.log(JSON.stringify({ event: "mapped", slug, pages: list.length }));
  }

  writeFileSync(
    join(OUT_DIR, "feature-map.json"),
    JSON.stringify(index, null, 2),
    "utf8",
  );
  writeFileSync(
    join(OUT_DIR, "FEATURE-MAP.md"),
    [
      `# Legacy → QLBD feature map`,
      ``,
      `- Mapped: ${index.mappedAt}`,
      `- Pages: ${index.pageCount}`,
      ``,
      `| slug | pages | file |`,
      `|------|------:|------|`,
      ...Object.entries(index.slugs).map(
        ([s, v]) => `| \`${s}\` | ${v.pageCount} | \`${v.path}\` |`,
      ),
      ``,
      `Feed: \`/docs-scan-cache\` → \`/qlbd-analy-demo\` · \`yarn scan-qlbd-demo\`.`,
      ``,
    ].join("\n"),
    "utf8",
  );

  console.log(
    JSON.stringify({
      event: "done",
      slugCount: Object.keys(index.slugs).length,
      out: FEAT_DIR,
    }),
  );
}

main();
